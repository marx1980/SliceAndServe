import type { OrderDefinition, ToolId } from '../src/game/model/types';

/** Authoring skeleton for a campaign level; the tuner picks the seed and fine-tunes the knobs. */
export interface LevelSpec {
  id: string;
  title: string;
  rows: number;
  columns: number;
  mask?: string[];
  /** Cakes per flavour, in flavour order (first entries of the flavour list). */
  cakes: number[];
  start: number;
  minSlices: number;
  maxSlices: number;
  maxFlavorsPerPlate: number;
  orders: OrderDefinition[];
  tools: ToolId[];
  /** Relief levels target an easier band than their neighbours. */
  relief?: boolean;
}

